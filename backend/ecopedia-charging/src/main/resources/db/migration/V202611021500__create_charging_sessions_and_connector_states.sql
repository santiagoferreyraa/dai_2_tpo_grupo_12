-- Tablas del componente SesionesDeCarga (ECO-60, RNF06).
--
-- Persisten el estado de sesión y el estado del conector bajo la misma transacción
-- declarativa que el estado de la reserva (bookings). Las operaciones contra sistemas
-- externos (distribuidora SOAP, pasarela de pagos REST y cargador físico) no participan
-- del rollback.

CREATE TABLE charging_sessions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             VARCHAR(64)   NOT NULL UNIQUE,
    booking_id             BIGINT,
    connector_id           BIGINT        NOT NULL,
    driver_id              BIGINT        NOT NULL,
    target_battery_percent INT           NOT NULL,
    power_limit_kw         NUMERIC(6, 2) NOT NULL,
    status                 VARCHAR(20)   NOT NULL,
    started_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    stopped_at             TIMESTAMP WITH TIME ZONE,
    kwh_delivered          NUMERIC(8, 3) NOT NULL DEFAULT 0.000,
    version                BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX idx_charging_sessions_connector ON charging_sessions (connector_id);
CREATE INDEX idx_charging_sessions_driver ON charging_sessions (driver_id);
CREATE INDEX idx_charging_sessions_booking ON charging_sessions (booking_id);

CREATE TABLE connector_states (
    connector_id       BIGINT PRIMARY KEY,
    status             VARCHAR(20) NOT NULL,
    current_session_id VARCHAR(64),
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    version            BIGINT NOT NULL DEFAULT 0
);
