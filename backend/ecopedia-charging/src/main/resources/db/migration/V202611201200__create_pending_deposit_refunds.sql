-- Señas cobradas que quedaron sin reserva y no se pudieron devolver en el acto (ECO-62).
--
-- Pasa en el checkout: se cobró la seña, la confirmación falló y la devolución en el acto tampoco
-- salió. Antes quedaba solo un ERROR en el log para devolverla a mano; ahora la devuelve el barrido de
-- las señas (DepositRefundProcessor). charge_id es único: el mismo cobro no se anota dos veces.

CREATE TABLE pending_deposit_refunds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_id   BIGINT         NOT NULL UNIQUE,
    driver_id   BIGINT         NOT NULL,
    amount      NUMERIC(10, 2) NOT NULL,
    hold_id     VARCHAR(40)    NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    refunded_at TIMESTAMP WITH TIME ZONE,
    version     BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_pending_deposit_refunds_open ON pending_deposit_refunds (refunded_at, created_at);
