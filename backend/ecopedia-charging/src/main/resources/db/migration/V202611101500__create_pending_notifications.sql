-- Los avisos de reservas que no se pudieron publicar en la cola notifications.dispatch porque el
-- broker no estaba (ECO-177, QA-27, DEF-01).
--
-- Nombre con timestamp, NUNCA V1/V2/V3. Ver README, "Migraciones".
--
-- Una fila por aviso pendiente. PendingNotificationRelay las publica en orden de llegada cuando el
-- broker vuelve y las borra; mientras tanto, cada intento fallido suma a attempts.

CREATE TABLE pending_notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- La clave de deduplicación del aviso (booking-<id>-<tipo>). Única: el mismo hecho no se encola
    -- dos veces, y si igual llegara dos veces a Notificaciones, ella guarda uno solo.
    event_id    VARCHAR(120)  NOT NULL UNIQUE,
    event_type  VARCHAR(40)   NOT NULL,
    booking_id  BIGINT        NOT NULL,
    -- El BookingEvent entero en JSON, tal como habría salido por la cola.
    payload     TEXT          NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts    INT           NOT NULL DEFAULT 0,
    last_error  VARCHAR(500)
);

CREATE INDEX idx_pending_notifications_created ON pending_notifications (created_at);
