-- Cobros de seña del componente Pagos (RF14, ECO-53).
--
-- Nombre con timestamp, NUNCA V1/V2/V3. Ver README, "Migraciones".
-- Sin calificar el schema: lo pone Flyway (spring.flyway.schemas=integration).
--
-- Cada fila es un intento de cobro que la pasarela CONTESTÓ, aprobado o rechazado. Un cobro sin
-- respuesta —pasarela caída o lenta— no deja fila: no se sabe si salió, y el reintento con la
-- misma clave es el que lo averigua.

CREATE TABLE deposit_charges (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- La clave con la que se pidió el cobro. UNIQUE es lo que hace idempotente la operación: el
    -- mismo pedido repetido encuentra la fila y devuelve el mismo resultado sin volver a cobrar.
    -- Es también la clave que viaja a la pasarela, que tiene su propia idempotencia por debajo.
    idempotency_key    VARCHAR(160)  NOT NULL UNIQUE,

    -- Conductor y tarjeta. Sin clave foránea al conductor, por el mismo motivo que
    -- payment_methods.driver_id. A la tarjeta sí podría tenerla, pero no hace falta: la baja de una
    -- tarjeta es lógica y la fila nunca se borra.
    driver_id          BIGINT        NOT NULL,
    payment_method_id  BIGINT        NOT NULL,

    -- Lo que se le muestra al conductor ("tu tarjeta terminada en 4242"), copiado al cobrar: si
    -- después da de baja la tarjeta, el cobro tiene que seguir diciendo con cuál se hizo.
    card_brand         VARCHAR(20)   NOT NULL,
    card_last_four     VARCHAR(4)    NOT NULL,

    amount             NUMERIC(10, 2) NOT NULL,

    -- A qué corresponde, para el log y la pasarela ("hold-<uuid>").
    reference          VARCHAR(120)  NOT NULL,

    -- APPROVED, DECLINED o REFUNDED.
    status             VARCHAR(20)   NOT NULL,

    -- Lo que contestó la pasarela. El id del cobro es nulo cuando lo rechazó sin crearlo.
    gateway_payment_id VARCHAR(80),
    status_detail      VARCHAR(80),

    gateway_refund_id  VARCHAR(80),

    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    refunded_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_deposit_charges_driver ON deposit_charges (driver_id);
