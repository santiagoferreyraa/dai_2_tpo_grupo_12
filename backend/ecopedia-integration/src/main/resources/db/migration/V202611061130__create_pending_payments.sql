-- Deudas y cobros pendientes del componente Pagos (RF02, RF14, RNF06, ECO-54).
-- Registra cobros de consumo no saldados que bloquean la habilitación de cargadores y reservas.

CREATE TABLE pending_payments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id          BIGINT         NOT NULL,
    payment_method_id  BIGINT,
    amount             NUMERIC(10, 2) NOT NULL,
    reason             VARCHAR(120)   NOT NULL,
    reference          VARCHAR(120)   NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    settled_at         TIMESTAMP WITH TIME ZONE,
    version            BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_pending_payments_driver_status ON pending_payments (driver_id, status);
