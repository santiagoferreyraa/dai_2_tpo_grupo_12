-- Agregado de telemetría por conector y franja de 15 minutos (ECO-301, RF16, RF19).
--
-- Una fila por conector y franja: lo que se guarda es el agregado, no las lecturas crudas. La
-- energía de la franja sale de la diferencia entre el acumulado de la sesión de una lectura y el
-- de la anterior (session_usage_stats guarda ese acumulado), así que cada kWh cae en una sola
-- franja aunque la lectura llegue repetida.
CREATE TABLE connector_demand_slots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connector_id      BIGINT         NOT NULL,
    slot_start        TIMESTAMP WITH TIME ZONE NOT NULL,
    station_id        BIGINT,
    station_name      VARCHAR(160),
    station_owner_id  BIGINT,
    connector_type    VARCHAR(32),
    energy_kwh        NUMERIC(10, 3) NOT NULL DEFAULT 0,
    peak_power_kw     NUMERIC(8, 2)  NOT NULL DEFAULT 0,
    sessions_started  INTEGER        NOT NULL DEFAULT 0,
    readings_count    INTEGER        NOT NULL DEFAULT 0,
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_connector_demand_slots UNIQUE (connector_id, slot_start)
);

CREATE INDEX idx_connector_demand_slots_slot
    ON connector_demand_slots (slot_start);

CREATE INDEX idx_connector_demand_slots_owner_slot
    ON connector_demand_slots (station_owner_id, slot_start);
