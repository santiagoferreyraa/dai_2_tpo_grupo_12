-- Proyección de uso por sesión construida desde el tópico telemetry.charging (ECO-301, RF16).
CREATE TABLE session_usage_stats (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id            VARCHAR(64)    NOT NULL UNIQUE,
    connector_id          BIGINT         NOT NULL,
    station_id            BIGINT,
    station_name          VARCHAR(160),
    station_owner_id      BIGINT,
    connector_type        VARCHAR(32),
    started_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reading_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at              TIMESTAMP WITH TIME ZONE,
    energy_kwh            NUMERIC(10, 3) NOT NULL DEFAULT 0,
    peak_power_kw         NUMERIC(8, 2)  NOT NULL DEFAULT 0,
    last_power_kw         NUMERIC(8, 2)  NOT NULL DEFAULT 0,
    last_battery_percent  NUMERIC(5, 2),
    status                VARCHAR(20)    NOT NULL,
    end_reason            VARCHAR(30),
    readings_count        INTEGER        NOT NULL DEFAULT 1,
    last_event_id         VARCHAR(64),
    version               BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_session_usage_stats_started_at
    ON session_usage_stats (started_at DESC);

CREATE INDEX idx_session_usage_stats_owner_started
    ON session_usage_stats (station_owner_id, started_at DESC);

CREATE INDEX idx_session_usage_stats_station
    ON session_usage_stats (station_id);
